import { findBreaking } from './gather.js';

/**
 * Generate DEV.md, CUSTOMER.md, LINKEDIN.md from release context.
 * Uses BYOK Anthropic/OpenAI when keys + provider set; otherwise
 * offline deterministic fallback from commit subjects.
 */

/**
 * @param {import('./gather.js').ReleaseContext} ctx
 * @param {object} config
 * @returns {Promise<{ mode: string, files: { dev: string, customer: string, linkedin: string } }>}
 */
export async function generateDocuments(ctx, config = {}) {
  const provider = resolveProvider(config);

  if (provider === 'anthropic' && config.anthropicApiKey) {
    try {
      const files = await generateWithAnthropic(ctx, config);
      return { mode: 'anthropic', files };
    } catch {
      // fall through to offline
    }
  }

  if (provider === 'openai' && config.openaiApiKey) {
    try {
      const files = await generateWithOpenAI(ctx, config);
      return { mode: 'openai', files };
    } catch {
      // fall through to offline
    }
  }

  return { mode: 'offline', files: generateOffline(ctx, config) };
}

/**
 * @param {object} config
 * @returns {'anthropic'|'openai'|'offline'}
 */
export function resolveProvider(config = {}) {
  const p = (config.llm?.provider || 'offline').toLowerCase();
  if (p === 'anthropic' && config.anthropicApiKey) return 'anthropic';
  if (p === 'openai' && config.openaiApiKey) return 'openai';
  if (p === 'anthropic' || p === 'openai') {
    // requested but no key → offline
    return 'offline';
  }
  return 'offline';
}

/**
 * Deterministic offline generation from commit subjects.
 * @param {import('./gather.js').ReleaseContext} ctx
 * @param {object} [config]
 */
export function generateOffline(ctx, config = {}) {
  const tag = ctx.tag || 'v0.0.0';
  const repo = ctx.repo || 'project';
  const commits = ctx.commits || [];
  const breaking = findBreaking(commits);
  const subjects = commits.map((c) => c.subject).filter(Boolean);
  const authors = [
    ...new Set(commits.map((c) => c.author).filter((a) => a && a !== 'unknown')),
  ];

  const features = subjects.filter((s) => /^(feat|feature)(\(.+\))?[!]?:/i.test(s));
  const fixes = subjects.filter((s) => /^(fix)(\(.+\))?[!]?:/i.test(s));
  const other = subjects.filter(
    (s) =>
      !/^(feat|feature|fix)(\(.+\))?[!]?:/i.test(s) &&
      !breaking.includes(s),
  );

  const bullet = (items, empty = '_None_') =>
    items.length ? items.map((i) => `- ${i}`).join('\n') : empty;

  const customerBullets = subjects.map((s) => `- ${humanizeSubject(s)}`);

  const dev = `# Developer Notes — ${tag}

## Summary
Release **${tag}** of \`${repo}\` includes **${commits.length}** commit(s).

${ctx.compareUrl ? `Compare: ${ctx.compareUrl}\n` : ''}
## Breaking changes
${bullet(breaking, '_None detected_')}

## Features
${bullet(features)}

## Fixes
${bullet(fixes)}

## Other
${bullet(other)}

## Commits
${
  commits.length
    ? commits.map((c) => `- \`${c.sha}\` ${c.subject}${c.author ? ` (${c.author})` : ''}`).join('\n')
    : '_No commits_'
}

## Authors
${authors.length ? authors.map((a) => `- ${a}`).join('\n') : '_Unknown_'}

---
Generated by SplitShip (offline) · Made By Zer01
`;

  const customer = `# What's New — ${tag}

Thanks for shipping with us. Here's what changed in **${tag}**:

${customerBullets.length ? customerBullets.join('\n') : '- Maintenance and internal improvements.'}

${
  breaking.length
    ? `\n## Important\n${breaking.map((b) => `- ${humanizeSubject(b)}`).join('\n')}\n`
    : ''
}
We appreciate your feedback — reply anytime.

—
The ${repo} team
`;

  const highlight =
    features[0] || fixes[0] || subjects[0] || 'new improvements across the board';
  const linkedin = `🚀 We just shipped **${tag}** of ${repo}.

Highlights:
${(features.length ? features : subjects).slice(0, 3).map((s) => `• ${humanizeSubject(s)}`).join('\n') || `• ${humanizeSubject(highlight)}`}

${breaking.length ? `⚠️ Note: this release includes breaking changes — check the notes before upgrading.\n\n` : ''}Built in public. Feedback welcome.

#buildinpublic #shipping #${slug(repo)}
`;

  return {
    dev: dev.trim() + '\n',
    customer: customer.trim() + '\n',
    linkedin: linkedin.trim() + '\n',
  };
}

/**
 * Turn conventional-commit subject into customer-friendly phrase.
 * @param {string} subject
 */
export function humanizeSubject(subject = '') {
  let s = String(subject).trim();
  s = s.replace(/^(feat|feature|fix|chore|docs|refactor|perf|test|build|ci|style)(\(.+?\))?[!]?:\s*/i, '');
  if (!s) return subject;
  return s.charAt(0).toUpperCase() + s.slice(1);
}

function slug(name = '') {
  return String(name).toLowerCase().replace(/[^a-z0-9]+/g, '');
}

async function generateWithAnthropic(ctx, config) {
  const model = config.llm?.model || 'claude-3-5-haiku-latest';
  const prompt = buildPrompt(ctx);
  const res = await fetch('https://api.anthropic.com/v1/messages', {
    method: 'POST',
    headers: {
      'content-type': 'application/json',
      'x-api-key': config.anthropicApiKey,
      'anthropic-version': '2023-06-01',
    },
    body: JSON.stringify({
      model,
      max_tokens: 4096,
      messages: [{ role: 'user', content: prompt }],
    }),
  });
  if (!res.ok) throw new Error(`Anthropic HTTP ${res.status}`);
  const data = await res.json();
  const text = (data.content || []).map((c) => c.text || '').join('');
  return parseLlmDocuments(text, ctx, config);
}

async function generateWithOpenAI(ctx, config) {
  const model = config.llm?.model || 'gpt-4o-mini';
  const prompt = buildPrompt(ctx);
  const res = await fetch('https://api.openai.com/v1/chat/completions', {
    method: 'POST',
    headers: {
      'content-type': 'application/json',
      authorization: `Bearer ${config.openaiApiKey}`,
    },
    body: JSON.stringify({
      model,
      messages: [{ role: 'user', content: prompt }],
      temperature: 0.3,
    }),
  });
  if (!res.ok) throw new Error(`OpenAI HTTP ${res.status}`);
  const data = await res.json();
  const text = data.choices?.[0]?.message?.content || '';
  return parseLlmDocuments(text, ctx, config);
}

function buildPrompt(ctx) {
  const commits = (ctx.commits || [])
    .map((c) => `- ${c.sha} ${c.subject}${c.author ? ` (${c.author})` : ''}`)
    .join('\n');
  return `You are SplitShip. Produce three markdown documents for release ${ctx.tag} of ${ctx.repo}.

Return EXACTLY this structure (no extra commentary):

<<<DEV>>>
...developer-facing release notes...
<<<CUSTOMER>>>
...customer-facing what's new...
<<<LINKEDIN>>>
...short LinkedIn post...

Commits:
${commits || '(none)'}
`;
}

function parseLlmDocuments(text, ctx, config) {
  const extract = (label) => {
    const re = new RegExp(`<<<${label}>>>\\s*([\\s\\S]*?)(?=<<<|$)`, 'i');
    const m = text.match(re);
    return m ? m[1].trim() : '';
  };
  const dev = extract('DEV');
  const customer = extract('CUSTOMER');
  const linkedin = extract('LINKEDIN');
  if (!dev || !customer || !linkedin) {
    return generateOffline(ctx, config);
  }
  return {
    dev: dev.endsWith('\n') ? dev : dev + '\n',
    customer: customer.endsWith('\n') ? customer : customer + '\n',
    linkedin: linkedin.endsWith('\n') ? linkedin : linkedin + '\n',
  };
}
